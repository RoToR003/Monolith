var LazyLoadQueueBase = class {
	constructor(parallelLimit = PARALLEL_LIMIT) {
		this.parallelLimit = parallelLimit;
		this.queueId = 0;
		this.queue = [];
		this.inProcess = /* @__PURE__ */ new Set();
		this.lockPromise = null;
		this.unlockResolve = null;
		this.log = logger("LL", LogTypes.Error);
		this.processQueue = throttle(() => this._processQueue(), 8, false);
	}
	clear() {
		this.inProcess.clear();
		this.queue.length = 0;
	}
	lock() {
		if (this.lockPromise) return;
		this.lockPromise = new Promise((resolve, reject) => {
			this.unlockResolve = resolve;
		});
	}
	unlock() {
		if (!this.unlockResolve) return;
		this.unlockResolve();
		this.unlockResolve = this.lockPromise = null;
		this.processQueue();
	}
	async processItem(item) {
		if (this.lockPromise) return;
		this.inProcess.add(item);
		try {
			await this.loadItem(item);
		} catch (err) {
			if (!IGNORE_ERRORS.has(err?.type)) this.log.error("loadMediaQueue error:", err);
		}
		this.inProcess.delete(item);
		this.processQueue();
	}
	loadItem(item) {
		return item.load();
	}
	getItem() {
		return this.queue.shift();
	}
	addElement(method, el) {
		this.queue[method](el);
		this.processQueue();
	}
	purgeDead() {
		for (let i = this.queue.length - 1; i >= 0; --i) {
			const item = this.queue[i];
			if (item.middleware && !item.middleware()) {
				this.queue.splice(i, 1);
				this.discardItem(item);
			}
		}
	}
	discardItem(item) {}
	_processQueue(item) {
		this.purgeDead();
		if (!this.queue.length || this.lockPromise || this.parallelLimit > 0 && this.inProcess.size >= this.parallelLimit) return;
		do {
			if (item) indexOfAndSplice(this.queue, item);
			else item = this.getItem();
			if (item) this.processItem(item);
			else break;
			item = null;
		} while (this.inProcess.size < this.parallelLimit && this.queue.length);
	}
	push(el) {
		this.purgeDead();
		this.addElement("push", el);
	}
	unshift(el) {
		this.purgeDead();
		this.addElement("unshift", el);
	}
};
